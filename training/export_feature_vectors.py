"""Emit Solidity parity vectors for the on-chain feature extractor."""

from __future__ import annotations

import json
import pathlib
import random

from features import SCALE, features_from_prices

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main() -> None:
    rng = random.Random(42)
    cases = []

    # the story from the demo, so the exact values used on camera are covered
    story = json.loads((ROOT / "training/story_trace.json").read_text())
    data = __import__("numpy").load(ROOT / "training/data.npz")
    for i, row in enumerate(story[:16]):
        end = i + 6
        window = [int(v) for v in data["story"][max(0, end - 8) : end]]
        cases.append((window, features_from_prices(window)))

    # random windows, including the 6-, 7- and 8-price cases
    for _ in range(60):
        n = rng.choice([6, 7, 8])
        price = 1000 * 10**8
        window = []
        for _ in range(n):
            price = max(10**6, int(price * (1 + rng.uniform(-0.06, 0.06))))
            window.append(price)
        cases.append((window, features_from_prices(window)))

    blocks = []
    for idx, (window, feats) in enumerate(cases):
        n = len(window)
        next_idx = 0 if n == 8 else n
        lines = [f"        {{ // vector {idx} (n={n})", "        uint256[8] memory ring;"]
        for i, p in enumerate(window):
            lines.append(f"        ring[{i}] = {p};")
        lines.append(f"        int256[6] memory got = SentinelFeatures.compute(ring, {next_idx}, {n});")
        for i, v in enumerate(feats):
            lines.append(f'        assertEq(got[{i}], {v}, "v{idx} f{i}");')
        lines.append("        }")
        blocks.append("\n".join(lines))

    out = "\n".join(
        [
            "// SPDX-License-Identifier: MIT",
            "// AUTO-GENERATED by training/export_feature_vectors.py -- do not edit.",
            "pragma solidity ^0.8.29;",
            "",
            'import { Test } from "forge-std/Test.sol";',
            'import { SentinelFeatures } from "../../src/lib/SentinelFeatures.sol";',
            "",
            "contract FeatureParityTest is Test {",
            "    function test_generated_vectors() public pure {",
            "\n".join(blocks),
            "    }",
            "}",
            "",
        ]
    )
    (ROOT / "test/generated/FeatureParity.t.sol").write_text(out)
    print(f"wrote {len(cases)} feature vectors")


if __name__ == "__main__":
    main()
