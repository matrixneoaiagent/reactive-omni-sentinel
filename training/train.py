"""Train, quantize and export the Sentinel risk model.

The model is a 4-6-1 MLP with ReLU hidden units and a bounded linear output.
It predicts the next 5-tick return (scaled and clamped to [-1, 1]); the policy
maps that prediction to a 0..10000 risk score.

Everything that reaches the chain is integer-only.  The exported weights are
quantized to 1e6 and the generated Solidity mirrors the Python forward pass
operation for operation, so the vault can recompute -- and therefore verify --
the score an agent submits.
"""

from __future__ import annotations

import argparse
import json
import pathlib

import numpy as np

from features import SCALE, clamp, trunc_div

ROOT = pathlib.Path(__file__).resolve().parent.parent
INPUTS = 6
HIDDEN = 8


# --------------------------------------------------------------------------- #
# float training
# --------------------------------------------------------------------------- #
def init_params(rng: np.random.Generator):
    w1 = rng.normal(0.0, np.sqrt(2.0 / INPUTS), size=(INPUTS, HIDDEN))
    b1 = np.zeros(HIDDEN)
    w2 = rng.normal(0.0, np.sqrt(2.0 / HIDDEN), size=HIDDEN)
    b2 = 0.0
    return w1, b1, w2, b2


def forward(x, w1, b1, w2, b2):
    z = x @ w1 + b1
    h = np.maximum(z, 0.0)
    o = h @ w2 + b2
    return o, h, z


def train(x, y, rng, epochs=200, lr=0.003, batch=512, verbose=False):
    n = len(x)
    w1, b1, w2, b2 = init_params(rng)
    params = [w1, b1, w2, np.array(b2)]
    m = [np.zeros_like(p) for p in params]
    v = [np.zeros_like(p) for p in params]
    beta1, beta2, eps = 0.9, 0.999, 1e-8
    step = 0

    # rare events matter more than the calm majority
    sw = np.where(np.abs(y) > 0.2, 3.0, 1.0)

    for epoch in range(epochs):
        order = rng.permutation(n)
        epoch_loss = 0.0
        for start in range(0, n, batch):
            idx = order[start : start + batch]
            xb, yb, wb = x[idx], y[idx], sw[idx]
            o, h, z = forward(xb, w1, b1, w2, float(params[3]))
            oc = np.clip(o, -1.0, 1.0)
            epoch_loss += float(np.sum(wb * (oc - yb) ** 2))
            err = (oc - yb) * wb * 2.0 / len(idx)
            do = err * ((o >= -1.0) & (o <= 1.0))
            dw2 = h.T @ do
            db2 = do.sum()
            dh = np.outer(do, w2) * (z > 0)
            dw1 = xb.T @ dh
            db1 = dh.sum(axis=0)
            grads = [dw1, db1, dw2, np.array(db2)]

            step += 1
            for i, (p, g) in enumerate(zip(params, grads)):
                m[i] = beta1 * m[i] + (1 - beta1) * g
                v[i] = beta2 * v[i] + (1 - beta2) * (g * g)
                mh = m[i] / (1 - beta1**step)
                vh = v[i] / (1 - beta2**step)
                p -= lr * mh / (np.sqrt(vh) + eps)

        if verbose and (epoch % 20 == 0 or epoch == epochs - 1):
            print(
                f"epoch {epoch:3d} loss {epoch_loss / n:.5f} "
                f"out [{oc.min():+.2f},{oc.max():+.2f}] "
                f"|w2| {np.abs(w2).max():.2f}"
            )

    return params


# --------------------------------------------------------------------------- #
# integer inference (mirrors Solidity)
# --------------------------------------------------------------------------- #
def tdiv(a, b):
    a = np.asarray(a, dtype=np.int64)
    return np.where(a < 0, -((-a) // b), a // b).astype(np.int64)


def quantize(params):
    w1, b1, w2, b2 = params
    return (
        np.rint(w1 * SCALE).astype(np.int64),
        np.rint(b1 * SCALE).astype(np.int64),
        np.rint(w2 * SCALE).astype(np.int64),
        int(np.rint(b2 * SCALE)),
    )


def quant_forward(x_int, q):
    w1, b1, w2, b2 = q
    x = np.asarray(x_int, dtype=np.int64)
    acc = np.tile(b1, (len(x), 1))
    for i in range(INPUTS):
        acc += tdiv(x[:, i : i + 1] * w1[i][None, :], SCALE)
    h = np.maximum(acc, 0)
    o = np.full(len(x), b2, dtype=np.int64)
    for j in range(HIDDEN):
        o += tdiv(h[:, j] * w2[j], SCALE)
    return np.clip(o, -SCALE, SCALE)


def score_bps_from_output(o: int) -> int:
    o = clamp(int(o), -SCALE, SCALE)
    return int((o + SCALE) * 10000 // (2 * SCALE))


# --------------------------------------------------------------------------- #
# export
# --------------------------------------------------------------------------- #
def canonical_json(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"))


def keccak_hex(data: bytes) -> str:
    from eth_utils import keccak

    return "0x" + keccak(data).hex()


def export_solidity(q, model_hash, out_path: pathlib.Path):
    w1, b1, w2, b2 = q
    weights = [
        "// SPDX-License-Identifier: MIT",
        "// AUTO-GENERATED by training/train.py -- do not edit by hand.",
        f"// model hash: {model_hash}",
        "pragma solidity ^0.8.29;",
        "",
        "library ModelWeights {",
        "    int256 internal constant SCALE = 1_000_000;",
        f"    bytes32 internal constant MODEL_HASH = {model_hash};",
        "",
    ]
    for i in range(INPUTS):
        for j in range(HIDDEN):
            weights.append(f"    int256 internal constant W_{i}_{j} = {int(w1[i][j])};")
    weights.append("")
    for j in range(HIDDEN):
        weights.append(f"    int256 internal constant B_{j} = {int(b1[j])};")
    weights.append("")
    for j in range(HIDDEN):
        weights.append(f"    int256 internal constant V_{j} = {int(w2[j])};")
    weights.append("")
    weights.append(f"    int256 internal constant B_OUT = {int(b2)};")
    weights.append("}")
    weights.append("")
    out_path.write_text("\n".join(weights))

    # ---- pure inference library ---------------------------------------- #
    model = [
        "// SPDX-License-Identifier: MIT",
        "// AUTO-GENERATED by training/train.py -- do not edit by hand.",
        f"// model hash: {model_hash}",
        "pragma solidity ^0.8.29;",
        "",
        "import { ModelWeights } from \"./ModelWeights.sol\";",
        "",
        "/// @notice Integer-only mirror of the Python forward pass.",
        "/// @dev Every term is divided by SCALE before the next addition, exactly",
        "///      like training/train.py and agent/model.py.",
        "library SentinelModel {",
        "    int256 internal constant SCALE = ModelWeights.SCALE;",
        "    bytes32 internal constant MODEL_HASH = ModelWeights.MODEL_HASH;",
        "",
        f"    function score(int256[{INPUTS}] memory f) internal pure returns (uint16) {{",
    ]
    for j in range(HIDDEN):
        terms = " + ".join(
            f"f[{i}] * ModelWeights.W_{i}_{j} / SCALE" for i in range(INPUTS)
        )
        model.append(f"        int256 h{j} = ModelWeights.B_{j} + {terms};")
        model.append(f"        if (h{j} < 0) h{j} = 0;")
    terms_out = " + ".join(f"h{j} * ModelWeights.V_{j} / SCALE" for j in range(HIDDEN))
    model.append(f"        int256 o = ModelWeights.B_OUT + {terms_out};")
    model.append("        if (o > SCALE) o = SCALE;")
    model.append("        if (o < -SCALE) o = -SCALE;")
    model.append("        return uint16(uint256((o + SCALE) * 10000 / (2 * SCALE)));")
    model.append("    }")
    model.append("}")
    model.append("")
    (out_path.parent / "SentinelModel.sol").write_text("\n".join(model))


def export_model_vectors(x_int, scores, out_path: pathlib.Path, count=80):
    rng = np.random.default_rng(99)
    idx = rng.choice(len(x_int), size=min(count, len(x_int)), replace=False)
    blocks = []
    for k, i in enumerate(idx):
        f = [int(v) for v in x_int[i]]
        blocks.append(
            "\n".join(
                [
                    f"        // vector {k}",
                    f"        f[0] = {f[0]};",
                    f"        f[1] = {f[1]};",
                    f"        f[2] = {f[2]};",
                    f"        f[3] = {f[3]};",
                    f"        f[4] = {f[4]};",
                    f"        f[5] = {f[5]};",
                    f"        assertEq(uint256(SentinelModel.score(f)), {int(scores[i])}, \"vector {k}\");",
                ]
            )
        )
    body = "\n".join(blocks)
    out_path.write_text(
        "\n".join(
            [
                "// SPDX-License-Identifier: MIT",
                "// AUTO-GENERATED by training/train.py -- do not edit by hand.",
                "pragma solidity ^0.8.29;",
                "",
                "import { Test } from \"forge-std/Test.sol\";",
                "import { SentinelModel } from \"../../src/lib/SentinelModel.sol\";",
                "",
                "contract ModelParityTest is Test {",
                "    function test_generated_vectors() public pure {",
                f"        int256[{INPUTS}] memory f;",
                body,
                "    }",
                "}",
                "",
            ]
        )
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(ROOT / "training/data.npz"))
    ap.add_argument("--epochs", type=int, default=200)
    ap.add_argument("--lr", type=float, default=0.003)
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args()

    d = np.load(args.data)
    x, y = d["train_x"], d["train_y"]
    tx, ty = d["test_x"], d["test_y"]
    story, story_feats = d["story"], d["story_feats"]

    # hold out 10% of train for early inspection
    rng = np.random.default_rng(args.seed)
    n_val = len(x) // 10
    perm = rng.permutation(len(x))
    val_idx, tr_idx = perm[:n_val], perm[n_val:]

    # the network trains on floats in [-1, 1]; the chain and the agent use the
    # same values scaled by 1e6
    params = train(
        x[tr_idx] / SCALE,
        y[tr_idx],
        rng,
        epochs=args.epochs,
        lr=args.lr,
        verbose=args.verbose,
    )
    q = quantize(params)

    # ----- metrics on the quantized model -------------------------------- #
    o_test = quant_forward(tx, q)
    pred = o_test / SCALE
    r2 = 1 - np.sum((ty - pred) ** 2) / np.sum((ty - ty.mean()) ** 2)
    mae = float(np.mean(np.abs(pred - ty)))

    score = np.array([score_bps_from_output(int(v)) for v in o_test])
    event = ty >= 0.3
    calm = ty <= 0.05
    recall = float(np.mean(score[event] >= 6500)) if event.any() else float("nan")
    false_alarm = float(np.mean(score[calm] >= 6500)) if calm.any() else float("nan")

    base_trigger = tx[:, 0] <= -200_000  # last tick fell 1%
    base_recall = float(np.mean(base_trigger[event])) if event.any() else float("nan")
    base_false = float(np.mean(base_trigger[calm])) if calm.any() else float("nan")

    metrics = {
        "model": f"sentinel-mlp-{INPUTS}-{HIDDEN}-1",
        "hidden": HIDDEN,
        "scale": SCALE,
        "train_samples": int(len(tr_idx)),
        "test_samples": int(len(tx)),
        "r2_test": round(float(r2), 4),
        "mae_test": round(mae, 4),
        "event_precision_recall_at_6500": {
            "event_rate_in_test": round(float(event.mean()), 4),
            "recall": round(recall, 4),
            "false_alarm_rate_on_calm": round(false_alarm, 4),
        },
        "baseline_last_tick_minus_1pct": {
            "recall": round(base_recall, 4),
            "false_alarm_rate_on_calm": round(base_false, 4),
        },
    }

    # ----- weights / hash / files ---------------------------------------- #
    w1, b1, w2, b2 = q
    weights_obj = {
        "version": "sentinel-mlp-v1",
        "inputs": INPUTS,
        "hidden": HIDDEN,
        "scale": SCALE,
        "w1": [[int(v) for v in row] for row in w1],
        "b1": [int(v) for v in b1],
        "w2": [int(v) for v in w2],
        "b2": int(b2),
    }
    blob = canonical_json(weights_obj).encode()
    model_hash = keccak_hex(blob)

    (ROOT / "training/weights.json").write_text(canonical_json(weights_obj) + "\n")
    (ROOT / "training/metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")
    export_solidity(q, model_hash, ROOT / "src/lib/ModelWeights.sol")
    export_model_vectors(tx, score, ROOT / "test/generated/ModelParity.t.sol")

    # ----- story trace ---------------------------------------------------- #
    rows = []
    mode = "NORMAL"
    for i, f in enumerate(story_feats):
        o = int(quant_forward(np.asarray([f], dtype=np.int64), q)[0])
        s = score_bps_from_output(o)
        if s >= 6500:
            mode = "DEFENSIVE"
        elif s <= 4000:
            mode = "NORMAL"
        rows.append({"tick": i + 6, "score": s, "mode": mode, "out": round(o / SCALE, 3)})

    print(f"model hash {model_hash}")
    print(json.dumps(metrics, indent=2))
    print("\nstory:")
    for r in rows:
        print(f"  tick {r['tick']:2d}  out {r['out']:+.3f}  score {r['score']:5d}  {r['mode']}")

    (ROOT / "training/story_trace.json").write_text(json.dumps(rows, indent=2) + "\n")
    (ROOT / "training/model_hash.txt").write_text(model_hash + "\n")


if __name__ == "__main__":
    main()
